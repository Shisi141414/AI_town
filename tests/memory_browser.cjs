const {chromium}=require('playwright');
const path=require('path');
let browser;
(async()=>{
 browser=await chromium.launch({channel:'msedge',headless:true});
 const page=await browser.newPage({viewport:{width:1440,height:1000}}),errors=[];
 page.on('pageerror',e=>errors.push(e.message));
 await page.goto('http://127.0.0.1:8303/');
 await page.locator('.pcard').first().waitFor();
 if(!await page.locator('.pcard').first().textContent().then(t=>t.includes('轻症')))throw Error('Missing illness status');
 const first=page.locator('.pcard').first(), second=page.locator('.pcard').nth(1);
 if(await first.locator('.resident-memory').evaluate(el=>el.open))throw Error('Memory should start collapsed');
 await first.locator('.resident-memory > summary').click();
 await first.locator('.mem-tier').selectOption('3');
 await first.locator('.mem-list .mi').first().waitFor();
 if(!await first.locator('.mem-stats').textContent().then(t=>t.includes('永久')))throw Error('Missing permanent layer');
 await first.locator('.mem-tier').selectOption('1');
 await first.locator('.mem-list .mi').first().waitFor();
 const before=await first.locator('.mem-list .mi').count();
 if(before!==40)throw Error('Expected paginated 40, got '+before);
 await first.locator('.mem-more').click();
 await page.waitForFunction(()=>document.querySelector('.pcard .mem-list').querySelectorAll('.mi').length>40);
 await page.evaluate(()=>renderPlayers());
 if(!await first.locator('.resident-memory').evaluate(el=>el.open))throw Error('Expanded memory collapsed on refresh');
 if(await first.locator('.mem-list .mi').count()<=40)throw Error('Loaded memories lost on refresh');
 await second.locator('.resident-memory > summary').click();
 if(await second.locator('.mem-tier').inputValue()!=='1')throw Error('Residents share memory tier');
 await first.locator('.mem-tier').selectOption('2');
 await first.locator('.mem-list .mi').first().waitFor();
 if(!await first.locator('.mem-list').textContent().then(t=>t.includes('L2')))throw Error('Missing second layer');
 await first.locator('.mem-tier').selectOption('1');
 await first.locator('.mem-list .mi').first().waitFor();
 if(!await first.locator('.mem-list').textContent().then(t=>t.includes('L1')))throw Error('Missing first layer');
 await first.screenshot({path:path.resolve('docs/previews/memory-system.png')});
 if(errors.length)throw Error(errors.join('\n'));
 console.log(JSON.stringify({result:'passed',residentMemoryPanel:true,perResidentTier:true,illnessStatus:true,consoleErrors:errors}));
 await browser.close();
})().catch(async e=>{console.error(e);if(browser)await browser.close();process.exitCode=1;});
