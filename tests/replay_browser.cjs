const {chromium}=require('playwright');
const path=require('path');
let browser;
(async()=>{
 browser=await chromium.launch({channel:'msedge',headless:true});
 const page=await browser.newPage({viewport:{width:1440,height:1000}}),errors=[];
 page.on('pageerror',e=>errors.push(e.message));
 const base='http://127.0.0.1:8301';
 await page.request.post(base+'/api/control',{data:{cmd:'reset'}});
 await page.goto(base);
 await page.waitForFunction(()=>document.querySelector('#clockbox').textContent.includes('08:00'));
 for(let i=0;i<6;i++)await page.request.post(base+'/api/control',{data:{cmd:'step'}});
 const before=await page.request.get(base+'/api/state').then(r=>r.json());
 await page.locator('nav [data-panel="replays"]').click();
 await page.locator('.history-recordings summary').click();
 await page.locator('#btnListReplays').click();
 await page.locator('#replayEntries details').first().locator('summary').click();
 await page.locator('#replayEntries [data-replay]').first().click();
 await page.waitForFunction(()=>document.querySelector('#modeTag').textContent.includes('只读回放'));
 if(!await page.locator('#btnStart').isDisabled())throw Error('Live start enabled during replay');
 if(!await page.locator('#btnReset').isDisabled())throw Error('Live reset enabled during replay');
 const max=await page.locator('#replaySeek').getAttribute('max');
 await page.locator('#replaySeek').evaluate((e,max)=>{e.value=max;e.dispatchEvent(new Event('input'));},max);
 await page.waitForFunction(max=>document.querySelector('#replayPosition').textContent.includes(`第 ${+max+1} /`),max);
 await page.screenshot({path:path.resolve('docs/previews/replay.png'),fullPage:true});
 await page.locator('#btnPlayReplay').click();
 await page.waitForFunction(()=>document.querySelector('#btnPlayReplay').textContent.includes('暂停'));
 await page.locator('#btnPlayReplay').click();
 const after=await page.request.get(base+'/api/state').then(r=>r.json());
 if(before.tick!==after.tick)throw Error('Replay advanced live clock');
 await page.locator('#btnExitReplay').click();
 await page.waitForFunction(()=>!document.querySelector('#modeTag').textContent.includes('只读回放'));
 await page.locator('#btnStep').click();
 await page.waitForFunction(()=>document.querySelector('#clockbox').textContent.includes('09:10'));
 if(errors.length)throw Error(errors.join('\n'));
 console.log(JSON.stringify({result:'passed',frames:+max+1,readonly:true,seek:true,playPause:true,returnToLive:true,consoleErrors:errors}));
 await browser.close();
})().catch(async e=>{console.error(e);if(browser)await browser.close();process.exitCode=1;});

