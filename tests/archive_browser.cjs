const {chromium}=require('playwright');
(async()=>{const browser=await chromium.launch({channel:'msedge',headless:true});try{
 const page=await browser.newPage({viewport:{width:1440,height:1000}}),errors=[];
 page.on('pageerror',e=>errors.push(e.message));const base='http://127.0.0.1:8301';
 await page.request.post(base+'/api/control',{data:{cmd:'reset'}});
 await page.request.post(base+'/api/control',{data:{cmd:'step'}});
 const id=(await (await page.request.post(base+'/api/saves/current')).json()).id;
 await page.goto(base);await page.locator('.pcard').first().waitFor();
 await page.locator('nav [data-panel="replays"]').click();
 if(await page.locator('#saveList,#replayList').count())throw Error('Archive dropdown still present');
 const entry=page.locator('#saveEntries details[data-id="'+id+'"]');await entry.locator('summary').click();
 if(await entry.locator('button').count()!==5)throw Error('Missing save actions');
 page.once('dialog',d=>d.accept('温馨小屋'));await entry.locator('[data-action="rename"]').click();
 await page.waitForFunction(id=>document.querySelector('#saveEntries details[data-id="'+id+'"] .archive-name').textContent==='温馨小屋',id);
 await entry.locator('[data-action="favorite"]').click();
 await page.waitForFunction(id=>document.querySelector('#saveEntries details').dataset.id===id&&document.querySelector('#saveEntries details .archive-name').textContent.includes('★'),id);
 await page.screenshot({path:require('path').resolve('docs/previews/saves.png'),fullPage:true});
 await entry.locator('[data-action="replay"]').click();
 await page.waitForFunction(()=>!document.querySelector('#btnContinueReplay').disabled);
 const frame=await page.locator('#replayPosition').textContent();
 page.once('dialog',d=>d.accept());await page.locator('#btnContinueReplay').click();
 await page.waitForFunction(()=>document.querySelector('#replayControls').hidden);
 const current=(await (await page.request.get(base+'/api/state')).json()).save_id;
 if(current===id)throw Error('Continuation overwrote source');
 page.once('dialog',d=>d.accept());await entry.locator('[data-action="delete"]').click();
 await entry.waitFor({state:'detached'});
 await page.setViewportSize({width:390,height:844});
 if(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth))throw Error('Mobile overflow');
 if(errors.length)throw Error(errors.join('\n'));
 console.log(JSON.stringify({result:'passed',fiveActions:true,favoriteFirst:true,rename:true,delete:true,frameContinuation:frame,mobile:true}));
}finally{await browser.close();}})().catch(e=>{console.error(e);process.exitCode=1});
