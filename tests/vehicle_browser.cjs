const {chromium}=require('playwright');
const path=require('path');
let browser;
(async()=>{
  const base=process.env.AI_TOWN_TEST_URL||'http://127.0.0.1:8302';
  browser=await chromium.launch({channel:'msedge',headless:true});
  const page=await browser.newPage({viewport:{width:1440,height:1000}});
  const errors=[];page.on('pageerror',e=>errors.push(e.message));
  await page.goto(base);await page.locator('.pcard').first().waitFor();
  const initial=await (await page.request.get(base+'/api/state')).json();
  const [a,b,c]=initial.players;
  await page.locator('#sceneTabs [data-scene="town"]').click();
  await page.locator('[data-mode="car"]').click();
  await page.waitForFunction(()=>document.querySelector('#carStatus').textContent.includes('使用中'));
  await page.locator('#travelResident').selectOption(b.pid);
  await page.locator('#boardCar:not([disabled])').waitFor();
  await page.locator('#boardCar').click();
  await page.locator('#leaveCar:not([disabled])').waitFor();
  let state=await (await page.request.get(base+'/api/state')).json();
  if(state.players.find(p=>p.pid===b.pid).vehicle_driver!==a.pid)throw Error('Boarding did not update engine');
  await page.locator('#travelResident').selectOption(a.pid);
  await page.waitForFunction(()=>document.querySelector('#rideInfo').textContent.includes('车上室友'));
  await page.locator('.travel-card').scrollIntoViewIfNeeded();
  await page.screenshot({path:path.resolve(__dirname,'../docs/previews/car-sharing.png'),fullPage:true,animations:'disabled'});
  await page.locator('#travelResident').selectOption(c.pid);
  await page.locator('#buyCar').click();
  await page.waitForFunction(()=>document.querySelector('#buyCar').textContent==='已拥有私家车');
  state=await (await page.request.get(base+'/api/state')).json();
  if(state.vehicles.length!==2||state.players.find(p=>p.pid===c.pid).stats.money!==200)throw Error('Purchase is not exactly 1000');
  await page.locator('#travelResident').selectOption(b.pid);
  await page.locator('#leaveCar').click();
  await page.locator('#leaveCar[disabled]').waitFor();
  if(errors.length)throw Error(errors.join('\n'));
  console.log(JSON.stringify({result:'passed',boarding:true,privateCarPurchase:1000,disembarking:true,consoleErrors:errors}));
  await browser.close();
})().catch(async e=>{console.error(e);if(browser)await browser.close();process.exitCode=1;});
