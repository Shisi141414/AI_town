const {chromium}=require('playwright');
(async()=>{const browser=await chromium.launch({channel:'msedge',headless:true});try{
 const page=await browser.newPage({viewport:{width:1440,height:900}}),errors=[];
 page.on('pageerror',e=>errors.push(e.message));
 await page.goto('http://127.0.0.1:8301/');
 await page.locator('#btnMechanics').click();
 await page.locator('#mechanicsDialog summary').filter({hasText:'所有活动'}).click();
 await page.locator('#mechanicsActivities summary').filter({hasText:'cook'}).first().click();
 await page.locator('input[data-activity-key="cook"][data-activity-scene="town"]').check();
 await page.locator('#mechanicsActivities summary').filter({hasText:'cook'}).first().evaluate(el=>el.parentElement.open=true);
 await page.locator('input[data-activity-key="cook"][data-activity-location="town:C"]').check();
 await page.locator('select[data-activity-key="cook"][data-activity-field="target_mode"]').selectOption('optional');
 await page.locator('input[data-activity-key="cook"][data-activity-field="self_affinity_per_tick"]').fill('2');
 await page.locator('input[data-activity-key="cook"][data-activity-field="target_affinity_per_tick"]').fill('1');
 await page.locator('#saveMechanics').click();
 const after=await page.request.get('http://127.0.0.1:8301/api/mechanics').then(r=>r.json());
 if(!after.activity_catalog.cook.places.town.includes('town:C')||after.activity_catalog.cook.target_mode!=='optional'||after.activity_catalog.cook.self_affinity_per_tick!==2)throw Error('Multi-place or target settings not saved');
 await page.locator('#closeMechanics').click();
 await page.evaluate(()=>openTownBuilding('S'));
 await page.locator('#shopEditor').waitFor({state:'visible'});
 await page.locator('#newShopCode').fill('seeds');await page.locator('#newShopName').fill('种子');
 await page.locator('#newShopPrice').fill('7');await page.locator('#addShopProduct').click();
 await page.locator('#saveShopProducts').click();
 const goods=await page.request.get('http://127.0.0.1:8301/api/town/shop').then(r=>r.json());
 if(goods.buy_seeds?.price!==7||goods.buy_seeds?.name!=='种子')throw Error('New shop item not saved');
 await page.waitForFunction(()=>document.querySelector('#buildingUnifiedActivities')?.textContent.includes('种子'));
 if(!await page.locator('#buildingUnifiedActivities').textContent().then(t=>t.includes('种子')&&t.includes('生命 0/刻')))throw Error('Building activity summary incomplete');
 await page.locator('input[data-shop-key="buy_seeds"][data-shop-field="enabled"]').uncheck();
 const noticesBefore=await page.locator('#eventNotifications .event-popup').filter({hasText:'商店货架已保存'}).count();
 await page.locator('#saveShopProducts').click();
 const shelf=await page.request.get('http://127.0.0.1:8301/api/town/shop').then(r=>r.json());
 if(shelf.buy_seeds.enabled)throw Error('Product off-shelf state not saved');
 await page.waitForFunction(before=>[...document.querySelectorAll('#eventNotifications .event-popup')].filter(el=>el.textContent.includes('商店货架已保存')).length>before,noticesBefore);
 await page.locator('#closeBuilding').click();
 await page.locator('#playerList details').filter({hasText:'最近一次模型提示词与原始回复'}).first().locator('summary').first().click();
 if(!await page.locator('#playerList').textContent().then(t=>t.includes('用户提示词')&&t.includes('原始回复')))throw Error('Resident prompt/reply expander missing');
 if(errors.length)throw Error(errors.join('; '));
 console.log('activity editor browser ok');
}finally{await browser.close();}})().catch(e=>{console.error(e);process.exit(1)});
