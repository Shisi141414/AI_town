const {chromium}=require('playwright');
(async()=>{const browser=await chromium.launch({channel:'msedge',headless:true});try{
 const page=await browser.newPage({viewport:{width:1440,height:900}}),errors=[];
 page.on('pageerror',e=>errors.push(e.message));
 await page.goto('http://127.0.0.1:8301/');
 await page.locator('#btnMechanics').click();
 await page.locator('#mechanicsDialog[open]').waitFor();
 const preview=await page.locator('#mechanicsPreview').inputValue();
 const headings=['# 本次决定','## 当前情况','## 已知信息','## 可选行动','## 行动方法','## 输出格式'];
 if(headings.map(h=>preview.indexOf(h)).some((at,i,all)=>at<0||(i&&at<=all[i-1])))throw Error('Prompt sections out of order');
 if(!preview.includes('action=visit')||!preview.includes('action=emoji')||!preview.includes('action=computer'))throw Error('Prompt discovery or tools absent');
 if(preview.includes('job_programmer')||preview.includes('hourly_wage'))throw Error('Remote job details leaked');
 const rules=(await page.request.get('http://127.0.0.1:8301/api/mechanics').then(r=>r.json())).rules;
 const catalog=(await page.request.get('http://127.0.0.1:8301/api/mechanics').then(r=>r.json())).activity_catalog;
 if(await page.locator('#mechanicsRules input').count()!==Object.keys(rules).length)throw Error('Rule fields missing');
 if(await page.locator('#mechanicsRules details').count()<6)throw Error('Rule categories missing');
 if(!await page.locator('#mechanicsRules').textContent().then(t=>t.includes('电话与社交费用')&&t.includes('通话每刻话费')&&t.includes('开车每刻油费')))throw Error('Per-tick fees missing');
 const labels=await page.locator('#mechanicsRules label').allTextContents();
 if(labels.some(t=>/^[a-z][a-z_]+$/.test(t.trim())))throw Error('Untranslated rule label');
 if(await page.locator('#mechanicsHours input').count()!==24)throw Error('Hours fields missing');
 if(!await page.locator('#mechanicsActivities').textContent().then(t=>t.includes('做饭')&&t.includes('睡觉')))throw Error('Activity list incomplete');
 const activities=await page.locator('#mechanicsActivities').textContent();
 if(!activities.includes('做爱')||!activities.includes('电脑游戏')||activities.includes('打游戏'))throw Error('Intimacy or game activity list wrong');
 if(await page.locator('#mechanicsActivities details').count()!==Object.keys(catalog).length)throw Error('Unified activity list incomplete');
 await page.locator('#mechanicsDialog summary').filter({hasText:'所有活动'}).click();
 await page.locator('#mechanicsActivities summary').filter({hasText:'cook'}).first().click();
 await page.locator('textarea[data-activity-key="cook"][data-activity-field="description"]').fill('在厨房；做一顿热饭');
 await page.locator('input[data-activity-key="cook"][data-activity-field="effects.hp"]').fill('0.25');
 await page.locator('#newActivityCode').fill('write_diary');
 await page.locator('#newActivityName').fill('写日记');
 await page.locator('#addMechanicsActivity').click();
 if(!await page.locator('[data-activity-key="write_diary"]').count())throw Error('New activity not added');
 await page.locator('#mechanicsRules summary').filter({hasText:'室外出行'}).click();
 await page.locator('input[data-mechanic="rules.walk_speed"]').fill('2');
 await page.locator('#saveMechanics').click();
 await page.waitForFunction(()=>document.querySelector('input[data-mechanic="rules.walk_speed"]').value==='2');
 if((await page.request.get('http://127.0.0.1:8301/api/mechanics').then(r=>r.json())).rules.walk_speed!==2)throw Error('Rule did not persist');
 const updated=await page.request.get('http://127.0.0.1:8301/api/mechanics').then(r=>r.json());
 if(updated.activity_descriptions.cook!=='在厨房；做一顿热饭'||!updated.prompt_preview.includes('在厨房；做一顿热饭'))throw Error('Edited action description not in model prompt');
 if(updated.activity_catalog.cook.effects.hp!==.25||!updated.activity_catalog.write_diary)throw Error('Unified activity edits did not persist');
 if(!updated.prompt_preview.includes('write_diary'))throw Error('New activity absent from model menu');
 await page.locator('#mechanicsActivities summary').filter({hasText:'cook'}).first().click();
 await page.locator('input[data-activity-key="cook"][data-activity-field="enabled"]').uncheck();
 await page.locator('#mechanicsActivities summary').filter({hasText:'write_diary'}).first().click();
 await page.locator('[data-delete-activity="write_diary"]').click();
 await page.locator('#saveMechanics').click();
 const removed=await page.request.get('http://127.0.0.1:8301/api/mechanics').then(r=>r.json());
 if(removed.activity_catalog.cook.enabled||removed.activity_catalog.write_diary||removed.prompt_preview.includes('- cook:'))throw Error('Disable or delete did not persist');
 await page.locator('#closeMechanics').click();
 if(errors.length)throw Error(errors.join('; '));
 console.log('mechanics browser ok');
}finally{await browser.close();}})().catch(e=>{console.error(e);process.exit(1)});
